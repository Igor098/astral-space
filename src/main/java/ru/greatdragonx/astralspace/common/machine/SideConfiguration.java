package ru.greatdragonx.astralspace.common.machine;

import java.util.Map;
import java.util.Objects;

/**
 * Неизменяемая конфигурация портов
 * на логических сторонах механизма.
 *
 * <p>Связывает логические стороны {@link MachineSide}
 * с соответствующими конфигурациями портов
 * {@link SidePortConfig}.</p>
 *
 * <p>Для каждой стороны может быть определена
 * не более чем одна конфигурация порта.
 * Наличие конфигурации для всех сторон
 * механизма не является обязательным.</p>
 *
 * <p>Конфигурация не зависит от мировой
 * ориентации механизма и не изменяется
 * при его горизонтальном повороте.</p>
 *
 * <p>Не управляет передачей ресурсов,
 * не проверяет физическую доступность портов
 * и не обращается к игровому миру.</p>
 *
 * @param ports конфигурации портов,
 *              индексированные по логическим
 *              сторонам механизма
 * @see MachineSide
 * @see SidePortConfig
 */
public record SideConfiguration(Map<MachineSide, SidePortConfig> ports) {
    /**
     * Создаёт неизменяемую конфигурацию
     * портов механизма.
     *
     * <p>Переданная карта защитно копируется.
     * Последующие изменения исходной карты
     * не влияют на созданную конфигурацию.</p>
     *
     * <p>Пустая конфигурация допускается.
     * Наличие записей для всех логических
     * сторон механизма не требуется.</p>
     *
     * <p>Порядок обхода записей возвращаемой
     * карты не гарантируется.</p>
     *
     * @param ports исходная карта конфигураций портов
     * @throws NullPointerException если ports равен
     *                              {@code null} либо
     *                              содержит ключи
     *                              или значения,
     *                              равные {@code null}
     */
    public SideConfiguration {
        Objects.requireNonNull(ports, "Ports configuration cannot be null");
        ports = Map.copyOf(ports);
    }
}
