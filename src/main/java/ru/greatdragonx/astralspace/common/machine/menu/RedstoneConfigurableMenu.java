package ru.greatdragonx.astralspace.common.machine.menu;

import net.minecraft.server.level.ServerPlayer;
import ru.greatdragonx.astralspace.common.machine.RedstoneControlMode;

/**
 * Контракт меню механизма, поддерживающего
 * изменение режима редстоун-управления.
 *
 * <p>Предоставляет единый способ изменения
 * режима {@link RedstoneControlMode} через
 * открытое игроком меню механизма.</p>
 *
 * <p>Позволяет обрабатывать запросы на изменение
 * режима независимо от конкретного типа
 * механизма и реализации его меню.</p>
 *
 * <p>Изменение режима выполняется на серверной
 * стороне в контексте соответствующего игрока.</p>
 *
 * <p>Конкретная реализация отвечает за применение
 * режима к обслуживаемому механизму и необходимые
 * побочные эффекты изменения его состояния.</p>
 *
 * @see RedstoneControlMode
 */
public interface RedstoneConfigurableMenu {
    /**
     * Обрабатывает запрос игрока на изменение
     * режима редстоун-управления механизмом.
     *
     * <p>Метод предназначен для вызова
     * на серверной стороне.</p>
     *
     * <p>Переданный игрок предоставляет контекст
     * для проверки допустимости изменения режима.</p>
     *
     * <p>Конкретная реализация определяет порядок
     * проверки запроса, применения режима,
     * сохранения и синхронизации состояния
     * обслуживаемого механизма.</p>
     *
     * @param player серверный игрок,
     *               запросивший изменение режима
     * @param mode   запрошенный режим редстоун-управления
     */
    void setRedstoneControlMode(ServerPlayer player, RedstoneControlMode mode);
}
