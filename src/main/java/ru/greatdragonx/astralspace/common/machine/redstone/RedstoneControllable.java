package ru.greatdragonx.astralspace.common.machine.redstone;

import org.jspecify.annotations.NonNull;

/**
 * Публичный контракт механизма, поддерживающего
 * управление работой посредством сигнала редстоуна.
 *
 * <p>Поддержка редстоун-контроля является необязательной
 * функциональностью механизма и не зависит от наличия
 * энергетического хранилища или типа выполняемых операций.</p>
 *
 * <p>Интерфейс предоставляет доступ к пользовательской
 * настройке режима управления, текущему состоянию
 * сигнала и результату проверки редстоун-политики.</p>
 *
 * <p>Конкретный механизм самостоятельно определяет
 * источник сигнала и операции, выполнение которых
 * ограничивается редстоуном.</p>
 *
 * <p>Разрешение работы со стороны редстоуна не гарантирует
 * фактическую готовность механизма к выполнению операции.</p>
 *
 * @see RedstoneControlMode
 * @see RedstoneController
 */
public interface RedstoneControllable {
    /**
     * Возвращает текущий режим управления редстоуном.
     *
     * <p>Получение режима не зависит от готовности
     * серверного окружения и наличия сигнала.</p>
     *
     * @return текущий режим управления редстоуном
     */
    @NonNull RedstoneControlMode getRedstoneControlMode();

    /**
     * Изменяет пользовательский режим управления редстоуном.
     *
     * <p>Изменение допускается только при готовности
     * серверного окружения механизма.</p>
     *
     * <p>Повторная установка текущего режима
     * не изменяет состояние механизма.</p>
     *
     * @param mode новый режим управления
     * @return {@code true}, если режим успешно изменён,
     * иначе {@code false}
     * @throws NullPointerException если mode равен {@code null}
     */
    boolean changeRedstoneControlMode(
        @NonNull RedstoneControlMode mode
    );

    /**
     * Определяет наличие актуального сигнала редстоуна
     * от предусмотренного механизмом источника.
     *
     * <p>При неготовности серверного окружения
     * возвращает {@code false}.</p>
     *
     * <p>Результат не зависит от установленного
     * режима управления редстоуном.</p>
     *
     * @return {@code true}, если сигнал присутствует
     * при готовом серверном окружении,
     * иначе {@code false}
     */
    boolean hasRedstoneSignal();

    /**
     * Определяет, запрещает ли текущая редстоун-политика
     * выполнение контролируемой операции механизма.
     *
     * <p>Учитывает установленный режим управления
     * и актуальное состояние сигнала.</p>
     *
     * <p>При неготовности серверного окружения
     * возвращает {@code false}, поскольку отсутствие
     * готовности не является запретом со стороны редстоуна.</p>
     *
     * <p>Возвращаемое значение не учитывает наличие энергии,
     * топлива, ресурсов, готовность физической конструкции
     * и другие условия выполнения операции.</p>
     *
     * @return {@code true}, если операция запрещена
     * редстоун-политикой, иначе {@code false}
     */
    boolean isRedstoneBlockingOperation();
}
