package ru.greatdragonx.astralspace.common.machine.visual;

/**
 * Тип визуального порта механизма.
 *
 * <p>Определяет категорию ресурса,
 * для которого предназначено визуальное
 * представление порта.</p>
 *
 * <p>Используется для выбора соответствующего
 * визуального представления ресурсного
 * подключения механизма.</p>
 *
 * <p>Не определяет направление передачи ресурса,
 * текущий режим работы, физическое расположение
 * и доступность порта.</p>
 *
 * <p>Наличие визуального порта определённого типа
 * само по себе не гарантирует поддержку передачи
 * соответствующего ресурса механизмом.</p>
 *
 * @see VisualPort
 */
public enum VisualPortType {
    /**
     * Визуальный порт энергетического подключения.
     *
     * <p>Представляет порт, предназначенный
     * для передачи энергии.</p>
     */
    ENERGY,
    /**
     * Визуальный порт жидкостного подключения.
     *
     * <p>Представляет порт, предназначенный
     * для передачи жидкостей.</p>
     */
    FLUID,
    /**
     * Визуальный порт предметного подключения.
     *
     * <p>Представляет порт, предназначенный
     * для передачи предметов.</p>
     */
    ITEM,
    /**
     * Визуальный порт газового подключения.
     *
     * <p>Представляет порт, предназначенный
     * для передачи газообразных ресурсов.</p>
     */
    GAS
}
