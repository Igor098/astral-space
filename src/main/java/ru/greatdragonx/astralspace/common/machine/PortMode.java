package ru.greatdragonx.astralspace.common.machine;

/**
 * Общий режим работы порта механизма.
 *
 * <p>Определяет разрешённые направления
 * передачи ресурсов относительно механизма.</p>
 *
 * <p>Поддерживает входящий, исходящий,
 * двунаправленный и отключённый режимы.</p>
 *
 * <p>Не определяет тип передаваемого ресурса,
 * физическое расположение порта, его текущую
 * доступность и ограничения передачи.</p>
 *
 * @see SidePortConfig
 * @see SideConfiguration
 */
public enum PortMode {
    /**
     * Отключённый режим порта.
     *
     * <p>Приём и выдача ресурсов запрещены.</p>
     */
    DISABLED,
    /**
     * Входящий режим порта.
     *
     * <p>Разрешает приём ресурсов механизмом
     * и запрещает их внешнее извлечение.</p>
     */
    INPUT,
    /**
     * Исходящий режим порта.
     *
     * <p>Разрешает выдачу ресурсов механизмом
     * и запрещает их внешний приём.</p>
     */
    OUTPUT,
    /**
     * Двунаправленный режим порта.
     *
     * <p>Разрешает как приём, так и выдачу
     * ресурсов механизмом.</p>
     */
    BOTH
}
