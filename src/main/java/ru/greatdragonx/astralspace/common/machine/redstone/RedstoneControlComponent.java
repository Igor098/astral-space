package ru.greatdragonx.astralspace.common.machine.redstone;

import org.jspecify.annotations.NonNull;

import java.util.Objects;

/**
 * Управляет режимом редстоун-контроля механизма.
 *
 * <p>Хранит текущий режим управления и определяет
 * разрешение работы на основании переданного
 * состояния сигнала редстоуна.</p>
 *
 * <p>По умолчанию используется режим
 * {@link RedstoneControlMode#IGNORE}.</p>
 *
 * <p>При фактическом изменении режима уведомляет
 * владельца посредством переданного callback.
 * При восстановлении сохранённого состояния
 * уведомление не выполняется.</p>
 *
 * <p>Компонент не определяет наличие сигнала
 * самостоятельно, не обращается к игровому миру
 * и не управляет выполнением операций механизма.</p>
 *
 * <p>Получение актуального сигнала, сохранение
 * состояния и определение операций, подлежащих
 * ограничению, являются ответственностью владельца.</p>
 *
 * <p>Предназначен для последовательного использования
 * в контексте одного механизма.
 * Не является потокобезопасным.</p>
 *
 * @see RedstoneControlMode
 */
public final class RedstoneControlComponent {
    private final Runnable onModeChanged;
    private RedstoneControlMode mode;

    /**
     * Создаёт компонент управления редстоуном.
     *
     * <p>Устанавливает первоначальный режим
     * {@link RedstoneControlMode#IGNORE}.</p>
     *
     * <p>Переданный обработчик сохраняется,
     * но не вызывается при создании компонента.</p>
     *
     * @param onModeChanged обработчик фактического
     *                      изменения режима управления
     * @throws NullPointerException если обработчик
     *                              равен {@code null}
     */
    public RedstoneControlComponent(
        @NonNull Runnable onModeChanged
    )
    {
        this.onModeChanged = Objects.requireNonNull(onModeChanged, "onModeChanged cannot be null");
        this.mode = RedstoneControlMode.IGNORE;
    }

    /**
     * Возвращает текущий режим управления редстоуном.
     *
     * <p>Не изменяет состояние компонента
     * и не вызывает обработчик изменения режима.</p>
     *
     * @return текущий режим управления,
     * никогда не равный {@code null}
     */
    public @NonNull RedstoneControlMode getMode() {
        return this.mode;
    }

    /**
     * Изменяет текущий режим управления редстоуном.
     *
     * <p>Если переданный режим совпадает с текущим,
     * состояние компонента не изменяется
     * и обработчик изменения не вызывается.</p>
     *
     * <p>При фактическом изменении новый режим
     * сохраняется, после чего однократно вызывается
     * обработчик изменения режима.</p>
     *
     * <p>На момент вызова обработчика новый режим
     * уже доступен посредством {@link #getMode()}.</p>
     *
     * <p>Если обработчик выбрасывает исключение,
     * оно передаётся вызывающему коду.
     * Сохранённый режим автоматически не откатывается.</p>
     *
     * @param mode новый режим управления редстоуном
     * @return {@code true}, если режим был изменён
     * и обработчик успешно завершился,
     * иначе {@code false}, если режим
     * уже был установлен
     * @throws NullPointerException если переданный
     *                              режим равен {@code null}
     */
    public boolean changeMode(
        @NonNull RedstoneControlMode mode
    )
    {
        Objects.requireNonNull(mode, "mode cannot be null");

        if (this.mode == mode) {
            return false;
        }

        this.mode = mode;
        this.onModeChanged.run();
        return true;
    }

    /**
     * Определяет, разрешает ли текущий режим
     * работу механизма при указанном состоянии
     * сигнала редстоуна.
     *
     * <p>Делегирует проверку текущему
     * {@link RedstoneControlMode}.</p>
     *
     * <p>Положительный результат означает разрешение
     * только со стороны редстоун-управления
     * и не гарантирует возможность фактической
     * работы механизма.</p>
     *
     * <p>Не изменяет состояние компонента
     * и не вызывает обработчик изменения режима.</p>
     *
     * @param hasSignal наличие внешнего сигнала редстоуна
     * @return {@code true}, если работа разрешена,
     * иначе {@code false}
     */
    public boolean allowsOperation(boolean hasSignal) {
        return this.mode.allowsOperation(hasSignal);
    }

    /**
     * Восстанавливает сохранённый режим управления
     * редстоуном без уведомления владельца.
     *
     * <p>Предназначен для восстановления состояния
     * компонента до начала его штатной работы.</p>
     *
     * <p>Переданный режим устанавливается независимо
     * от текущего значения. Обработчик изменения
     * режима не вызывается даже при фактическом
     * изменении состояния.</p>
     *
     * <p>Чтение сохранённых данных, их преобразование
     * в режим управления и обработка некорректных
     * значений являются ответственностью владельца.</p>
     *
     * @param mode восстанавливаемый режим управления
     * @throws NullPointerException если переданный
     *                              режим равен {@code null}
     */
    public void restoreMode(
        @NonNull RedstoneControlMode mode
    )
    {
        Objects.requireNonNull(mode, "mode cannot be null");
        this.mode = mode;
    }
}
