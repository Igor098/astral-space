package ru.greatdragonx.astralspace.common.machine.redstone;

/**
 * Режим управления работой механизма
 * посредством сигнала редстоуна.
 *
 * <p>Определяет, разрешена ли работа механизма
 * в зависимости от наличия внешнего сигнала
 * редстоуна.</p>
 *
 * <p>Поддерживает игнорирование сигнала,
 * работу при наличии сигнала и работу
 * при его отсутствии.</p>
 *
 * <p>Режим определяет только разрешение
 * со стороны редстоун-управления и не гарантирует
 * возможность фактической работы механизма.</p>
 *
 * <p>Не обращается к игровому миру, не определяет
 * наличие сигнала самостоятельно и не управляет
 * состоянием механизма.</p>
 */
public enum RedstoneControlMode {
    /**
     * Игнорирование сигнала редстоуна.
     *
     * <p>Работа механизма разрешена независимо
     * от наличия внешнего сигнала.</p>
     */
    IGNORE,
    /**
     * Управление по наличию сигнала редстоуна.
     *
     * <p>Работа механизма разрешена только
     * при наличии внешнего сигнала.</p>
     */
    WHEN_POWERED,
    /**
     * Управление по отсутствию сигнала редстоуна.
     *
     * <p>Работа механизма разрешена только
     * при отсутствии внешнего сигнала.</p>
     */
    WHEN_UNPOWERED;

    /**
     * Определяет, разрешена ли работа механизма
     * при указанном состоянии сигнала редстоуна.
     *
     * <p>Результат зависит только от текущего
     * режима управления и переданного состояния
     * сигнала.</p>
     *
     * <p>Метод не проверяет остальные условия
     * работы механизма, включая наличие энергии,
     * топлива, ресурсов и свободной ёмкости
     * внутренних хранилищ.</p>
     *
     * <p>Не изменяет состояние механизма
     * и не имеет побочных эффектов.</p>
     *
     * @param hasSignal наличие внешнего сигнала редстоуна
     * @return {@code true}, если режим разрешает работу
     * при указанном состоянии сигнала,
     * иначе {@code false}
     */
    public boolean allowsOperation(boolean hasSignal) {
        return switch (this) {
            case IGNORE -> true;
            case WHEN_POWERED -> hasSignal;
            case WHEN_UNPOWERED -> !hasSignal;
        };
    }
}
