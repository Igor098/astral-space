package ru.greatdragonx.astralspace.common.machine;

/**
 * Логическая сторона механизма относительно
 * его собственной ориентации.
 *
 * <p>Используется для описания расположения
 * портов, элементов конфигурации и визуальных
 * компонентов независимо от ориентации
 * механизма в игровом мире.</p>
 *
 * <p>Логическая сторона не является абсолютным
 * мировым направлением. При повороте механизма
 * соответствующее мировое направление изменяется,
 * а логическая сторона сохраняется.</p>
 *
 * <p>Верхняя и нижняя стороны сохраняют свои
 * мировые направления при горизонтальном
 * повороте механизма.</p>
 *
 * <p>Преобразование между логическими сторонами
 * и мировыми направлениями выполняется
 * посредством {@link MachineSideDirections}.</p>
 *
 * @see MachineSideDirections
 */
public enum MachineSide {
    /**
     * Передняя сторона механизма.
     *
     * <p>Соответствует направлению его ориентации.</p>
     */
    FRONT,
    /**
     * Задняя сторона механизма.
     *
     * <p>Соответствует направлению, противоположному
     * направлению ориентации механизма.</p>
     */
    BACK,
    /**
     * Левая сторона механизма.
     *
     * <p>Соответствует направлению, полученному
     * поворотом направления ориентации механизма
     * на 90 градусов по часовой стрелке.</p>
     */
    LEFT,
    /**
     * Правая сторона механизма.
     *
     * <p>Соответствует направлению, полученному
     * поворотом направления ориентации механизма
     * на 90 градусов против часовой стрелки.</p>
     */
    RIGHT,
    /**
     * Верхняя сторона механизма.
     *
     * <p>Соответствует мировому направлению UP
     * независимо от горизонтальной ориентации.</p>
     */
    TOP,
    /**
     * Нижняя сторона механизма.
     *
     * <p>Соответствует мировому направлению DOWN
     * независимо от горизонтальной ориентации.</p>
     */
    BOTTOM
}
