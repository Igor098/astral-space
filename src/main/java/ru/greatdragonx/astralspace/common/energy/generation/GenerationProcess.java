package ru.greatdragonx.astralspace.common.energy.generation;

/**
 * Определяет производственный процесс генератора энергии.
 *
 * <p>Представляет стратегию производственного процесса,
 * позволяющую отделить общий алгоритм работы генератора
 * от конкретного способа производства энергии.</p>
 *
 * <p>Производственный процесс отвечает за подготовку
 * производственного тика и обработку его успешного
 * завершения.</p>
 *
 * <p>Конкретные реализации могут использовать топливные
 * циклы, внешние условия или другие механизмы,
 * необходимые для производства энергии.</p>
 *
 * <p>Производственный процесс не отвечает за хранение
 * и передачу энергии, управление энергетическими портами,
 * бюджетами передачи и проверку общих условий работы
 * генератора.</p>
 *
 * <p>Управление последовательностью вызовов методов
 * осуществляется владельцем производственного процесса.</p>
 */
public interface GenerationProcess {
    /**
     * Подготавливает производственный процесс
     * к выполнению одного производственного тика.
     *
     * <p>Метод вызывается после проверки общих условий
     * работы генератора, включая наличие свободного места
     * для полной порции производимой энергии
     * и разрешение работы редстоуном.</p>
     *
     * <p>В зависимости от реализации метод может изменять
     * состояние производственного процесса, например
     * списывать топливо и запускать новый топливный цикл.</p>
     *
     * <p>Успешная подготовка разрешает производство энергии,
     * но сама по себе не означает успешного завершения
     * производственного тика.</p>
     *
     * <p>Метод самостоятельно не производит энергию
     * и не выполняет операцию завершения
     * производственного тика.</p>
     *
     * @return {@code true}, если производственный процесс
     * готов к выполнению производственного тика;
     * {@code false}, если производство
     * в текущем тике невозможно
     */
    boolean prepareProductionTick();

    /**
     * Уведомляет производственный процесс об успешном
     * завершении одного производственного тика.
     *
     * <p>Метод должен вызываться ровно один раз после
     * успешной подготовки производственного процесса
     * и фактического сохранения полной порции
     * произведённой энергии.</p>
     *
     * <p>Конкретная реализация может изменять внутреннее
     * состояние производственного процесса, например
     * уменьшать количество оставшихся оплаченных
     * производственных тиков.</p>
     *
     * <p>Метод не должен вызываться, если производство
     * энергии было пропущено либо не завершилось успешно.</p>
     *
     * <p>Метод самостоятельно не производит
     * и не передаёт энергию.</p>
     */
    void onProductionTickCompleted();
}
