package ru.greatdragonx.astralspace.common.energy.generation;

import net.minecraft.world.level.storage.ValueInput;
import net.minecraft.world.level.storage.ValueOutput;
import org.jspecify.annotations.NonNull;

public interface PersistentGenerationProcess extends GenerationProcess {
    /**
     * Сохраняет текущее состояние производственного процесса
     * в предоставленный {@link ValueOutput}.
     *
     * <p>Переданный объект представляет готовую секцию
     * {@code generation_process}. Создание этой внешней
     * секции не входит в ответственность метода.</p>
     *
     * <p>Реализация может создавать собственные вложенные
     * секции и делегировать сохранение состояния
     * принадлежащим ей компонентам.</p>
     *
     * <p>Операция не должна изменять состояние
     * производственного процесса, запускать производство
     * или вызывать уведомления об изменении состояния.</p>
     *
     * <p>Для постоянного сохранения должно использоваться
     * подтверждённое состояние производственного процесса,
     * а не предварительное состояние незавершённых
     * транзакций.</p>
     *
     * @param output выходной объект для записи состояния
     *               производственного процесса
     * @throws NullPointerException если output равен
     *                              {@code null}
     */
    void saveState(@NonNull ValueOutput output);

    /**
     * Восстанавливает состояние производственного процесса
     * из предоставленного {@link ValueInput}.
     *
     * <p>Переданный объект представляет готовую секцию
     * {@code generation_process} либо пустой объект чтения,
     * если соответствующая секция отсутствует.</p>
     *
     * <p>Реализация самостоятельно обрабатывает отсутствие
     * и некорректность сохранённых данных согласно
     * контрактам принадлежащих ей компонентов.</p>
     *
     * <p>Восстановление должно выполняться тихо,
     * без запуска производственного процесса, списания
     * топлива, вызова уведомлений об изменении состояния
     * и взаимодействия с игровым миром.</p>
     *
     * <p>Метод предназначен для восстановления состояния
     * до начала штатной работы производственного процесса
     * и при отсутствии незавершённых транзакций,
     * затрагивающих восстанавливаемое состояние.</p>
     *
     * @param input входной объект с сохранённым состоянием
     *              производственного процесса
     * @throws NullPointerException если input равен
     *                              {@code null}
     */
    void restoreState(@NonNull ValueInput input);
}
