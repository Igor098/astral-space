package ru.greatdragonx.astralspace.common.energy.port;

/**
 * Определяет допустимое направление передачи энергии
 * через энергетический порт механизма.
 *
 * <p>Каждый порт может работать только в одном направлении:
 * принимать энергию, отдавать энергию либо быть отключённым.</p>
 *
 * <p>Режим не определяет, доступен ли порт физически,
 * можно ли изменять его настройки и должен ли механизм
 * активно передавать энергию соседям.</p>
 */
public enum EnergyPortMode {
    /**
     * Порт принимает энергию.
     */
    INPUT,

    /**
     * Порт отдаёт энергию.
     */
    OUTPUT,

    /**
     * Передача энергии через порт запрещена.
     */
    DISABLED;

    /**
     * Проверяет, разрешён ли приём энергии через порт.
     *
     * @return {@code true}, если режим равен {@link #INPUT}
     */
    public boolean allowsInsert() {
        return this == INPUT;
    }

    /**
     * Проверяет, разрешена ли выдача энергии через порт.
     *
     * @return {@code true}, если режим равен {@link #OUTPUT}
     */
    public boolean allowsExtract() {
        return this == OUTPUT;
    }
}
