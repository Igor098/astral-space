package ru.greatdragonx.astralspace.common.energy;

/**
 * Компонент учёта фактической скорости передачи энергии.
 *
 * <p>Накапливает количество переданной энергии
 * в пределах одного игрового тика и предоставляет
 * итоговое значение за предыдущий игровой тик.</p>
 *
 * <p>Использование завершённого игрового тика
 * позволяет избежать отображения промежуточных
 * значений, возникающих при выполнении нескольких
 * операций передачи в течение текущего тика.</p>
 *
 * <p>Если в предыдущем игровом тике передача
 * энергии отсутствовала, возвращается нулевая
 * скорость передачи.</p>
 *
 * <p>Компонент самостоятельно не участвует
 * в транзакциях. Владелец должен регистрировать
 * только окончательно подтверждённые операции
 * передачи энергии.</p>
 *
 * <p>Не хранит энергию, не ограничивает объём
 * передачи и не управляет энергетическими портами.</p>
 */
public final class EnergyTransferTracker {
    /**
     * Последний игровой тик, в котором была
     * зарегистрирована положительная передача энергии.
     */
    private long lastTransferTick = -1L;
    /**
     * Суммарное количество энергии, переданной
     * в последнем учтённом игровом тике.
     */
    private int transferredInLastTransferTick = 0;
    /**
     * Суммарное количество энергии, переданной
     * в игровом тике, непосредственно предшествующем
     * последнему учтённому тику.
     *
     * <p>Равно нулю, если в предшествующем
     * игровом тике передача отсутствовала.</p>
     */
    private int transferredInPrecedingTick = 0;

    /**
     * Регистрирует фактически переданное количество
     * энергии в указанном игровом тике.
     *
     * <p>При нескольких операциях передачи в пределах
     * одного тика их значения суммируются.</p>
     *
     * <p>При переходе к следующему игровому тику
     * накопленное значение сохраняется в качестве
     * результата предыдущего тика.</p>
     *
     * <p>Если между зарегистрированными операциями
     * передачи пропущен хотя бы один игровой тик,
     * результат предыдущего тика сбрасывается
     * в {@code 0}.</p>
     *
     * <p>Нулевые и отрицательные значения
     * игнорируются без изменения состояния.</p>
     *
     * <p>Метод должен вызываться только после
     * окончательного подтверждения передачи энергии.
     * Самостоятельный транзакционный откат
     * зарегистрированных значений не поддерживается.</p>
     *
     * @param amount      фактически переданное количество энергии
     * @param currentTick текущий игровой тик
     */
    public void recordTransfer(int amount, long currentTick)
    {
        if (amount <= 0) {
            return;
        }

        if (this.lastTransferTick != currentTick) {
            this.transferredInPrecedingTick =
                this.lastTransferTick == currentTick - 1 ? this.transferredInLastTransferTick : 0;

            this.lastTransferTick = currentTick;
            this.transferredInLastTransferTick = 0;
        }

        this.transferredInLastTransferTick += amount;
    }

    /**
     * Возвращает суммарное количество энергии,
     * переданной за игровой тик, непосредственно
     * предшествующий указанному текущему тику.
     *
     * <p>Передачи, зарегистрированные в течение
     * текущего тика, не учитываются в возвращаемом
     * значении.</p>
     *
     * <p>Если в предыдущем игровом тике передача
     * отсутствовала, возвращает {@code 0}.</p>
     *
     * <p>Метод не изменяет внутреннее состояние
     * компонента и не требует обязательной регистрации
     * передачи в каждом игровом тике.</p>
     *
     * @param currentTick текущий игровой тик
     * @return фактическая скорость передачи энергии
     * за предыдущий игровой тик в FE/t
     */
    public int getCurrentTransferRate(long currentTick) {
        if (this.lastTransferTick == currentTick) {
            return this.transferredInPrecedingTick;
        }

        if (this.lastTransferTick == currentTick - 1) {
            return this.transferredInLastTransferTick;
        }

        return 0;
    }
}
