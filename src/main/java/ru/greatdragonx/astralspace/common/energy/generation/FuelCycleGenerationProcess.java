package ru.greatdragonx.astralspace.common.energy.generation;

import net.minecraft.world.level.storage.ValueInput;
import net.minecraft.world.level.storage.ValueOutput;
import net.neoforged.neoforge.transfer.transaction.Transaction;
import net.neoforged.neoforge.transfer.transaction.TransactionContext;
import org.jspecify.annotations.NonNull;

import java.util.Objects;
import java.util.OptionalInt;

/**
 * Реализует производственный процесс генератора,
 * основанный на оплаченных топливных циклах.
 *
 * <p>Координирует взаимодействие между компонентом
 * топливного цикла {@link FuelCycleComponent}
 * и операцией потребления топлива {@link FuelConsumption}.</p>
 *
 * <p>При наличии активного топливного цикла разрешает
 * выполнение производственного тика без повторного
 * потребления топлива.</p>
 *
 * <p>При отсутствии активного цикла пытается списать
 * необходимое количество топлива и транзакционно
 * запустить новый топливный цикл.</p>
 *
 * <p>Списание топлива и запуск нового цикла выполняются
 * в рамках одной корневой транзакции. Это обеспечивает
 * совместное подтверждение или откат соответствующих
 * изменений при соблюдении транзакционного контракта
 * источником топлива.</p>
 *
 * <p>Компонент самостоятельно не хранит счётчики
 * топливного цикла, не определяет конкретный вид
 * и необходимое количество топлива.</p>
 *
 * <p>Процесс не отвечает за производство, хранение
 * и передачу энергии, управление энергетическими
 * портами, редстоуном и взаимодействие
 * с игровым миром.</p>
 *
 * <p>Реализует {@link PersistentGenerationProcess},
 * делегируя сохранение и восстановление состояния
 * компоненту топливного цикла.</p>
 *
 * <p>Не предназначен для одновременного использования
 * из нескольких потоков.</p>
 *
 * @see FuelCycleComponent
 * @see FuelConsumption
 * @see GenerationProcess
 * @see PersistentGenerationProcess
 */
public final class FuelCycleGenerationProcess implements PersistentGenerationProcess {
    private static final String FUEL_CYCLE_KEY = "fuel_cycle";

    private final FuelCycleComponent fuelCycle;
    private final FuelConsumption fuelConsumption;

    /**
     * Создаёт производственный процесс,
     * основанный на топливных циклах.
     *
     * <p>Принимает готовый компонент топливного цикла
     * и операцию потребления топлива, которые будут
     * использоваться на протяжении всего времени
     * существования производственного процесса.</p>
     *
     * <p>Конструктор самостоятельно не создаёт
     * и не изменяет состояние переданных компонентов,
     * не списывает топливо и не запускает новый
     * топливный цикл.</p>
     *
     * @param fuelCycle       компонент управления
     *                        состоянием топливного цикла
     * @param fuelConsumption транзакционная операция
     *                        потребления топлива
     * @throws NullPointerException если одна из переданных
     *                              зависимостей равна
     *                              {@code null}
     */
    public FuelCycleGenerationProcess(FuelCycleComponent fuelCycle, FuelConsumption fuelConsumption)
    {
        this.fuelCycle = Objects.requireNonNull(fuelCycle, "fuelCycle cannot be null");
        this.fuelConsumption = Objects.requireNonNull(
            fuelConsumption,
            "fuelConsumption cannot be null"
        );
    }

    /**
     * Подготавливает топливный производственный процесс
     * к выполнению одного производственного тика.
     *
     * <p>Если топливный цикл уже активен, метод немедленно
     * возвращает {@code true}, не открывая транзакцию,
     * не потребляя дополнительное топливо и не изменяя
     * состояние топливного цикла.</p>
     *
     * <p>Если активный цикл отсутствует, метод открывает
     * корневую транзакцию и пытается списать необходимое
     * количество топлива посредством {@link FuelConsumption}.</p>
     *
     * <p>При успешном полном списании топлива полученная
     * длительность передаётся в
     * {@link FuelCycleComponent#start(int, TransactionContext)}
     * для запуска нового цикла в рамках той же транзакции.</p>
     *
     * <p>Транзакция подтверждается только после успешного
     * списания топлива и запуска топливного цикла.</p>
     *
     * <p>При невозможности полного списания топлива
     * транзакция закрывается без подтверждения.
     * Предварительные изменения отменяются,
     * а метод возвращает {@code false}.</p>
     *
     * <p>При возникновении исключения до подтверждения
     * транзакции предварительные транзакционные изменения
     * отменяются. Исключение передаётся вызывающему коду
     * без преобразования в штатный отрицательный
     * результат.</p>
     *
     * <p>Метод не производит энергию и не уменьшает
     * количество оставшихся производственных тиков.
     * Расход оплаченного производственного тика
     * выполняется отдельно после успешного производства
     * полной порции энергии.</p>
     *
     * <p>При необходимости запуска нового цикла
     * метод самостоятельно открывает корневую транзакцию,
     * поэтому должен вызываться вне другой открытой
     * транзакции на текущем потоке.</p>
     *
     * @return {@code true}, если существует активный
     * топливный цикл либо удалось успешно
     * запустить новый;
     * {@code false}, если необходимое количество
     * топлива не удалось списать
     * @throws IllegalArgumentException если операция
     *                                  потребления топлива
     *                                  возвращает нулевую
     *                                  или отрицательную
     *                                  длительность
     * @throws NullPointerException     если операция
     *                                  потребления топлива
     *                                  возвращает {@code null}
     */
    @Override
    public boolean prepareProductionTick() {
        if (this.fuelCycle.isActive()) {
            return true;
        }

        try (Transaction transaction = Transaction.openRoot()) {
            OptionalInt duration = this.fuelConsumption.tryConsume(transaction);
            if (duration.isEmpty()) {
                return false;
            }

            this.fuelCycle.start(duration.getAsInt(), transaction);
            transaction.commit();
        }

        return true;
    }

    /**
     * Обрабатывает успешное завершение одного
     * производственного тика.
     *
     * <p>Делегирует расход одного оплаченного
     * производственного тика компоненту
     * {@link FuelCycleComponent}.</p>
     *
     * <p>Уменьшает количество оставшихся производственных
     * тиков ровно на единицу, не изменяя первоначальную
     * длительность топливного цикла.</p>
     *
     * <p>Метод должен вызываться после успешного
     * сохранения полной порции произведённой энергии.</p>
     *
     * <p>Операция не открывает транзакцию, не списывает
     * дополнительное топливо и не запускает автоматически
     * новый цикл при завершении текущего.</p>
     *
     * <p>После расходования последнего оплаченного тика
     * новый топливный цикл может быть запущен только
     * при следующем вызове
     * {@link #prepareProductionTick()}.</p>
     *
     * @throws IllegalStateException если активный
     *                               топливный цикл
     *                               отсутствует
     */
    @Override
    public void onProductionTickCompleted() {
        this.fuelCycle.completeProductionTick();
    }

    /**
     * Сохраняет состояние топливного производственного
     * процесса.
     *
     * <p>Создаёт вложенную секцию {@code fuel_cycle}
     * в предоставленном объекте записи и делегирует
     * непосредственную сериализацию состояния
     * компоненту {@link FuelCycleComponent}.</p>
     *
     * <p>Сохраняет состояние независимо от наличия
     * активного топливного цикла, включая пустое
     * состояние и завершённый цикл.</p>
     *
     * <p>Структура сохраняемых данных:</p>
     *
     * <pre>
     * fuel_cycle
     * ├── remaining_ticks: int
     * └── total_ticks: int
     * </pre>
     *
     * <p>Метод не создаёт внешнюю секцию
     * {@code generation_process}, не изменяет состояние
     * производственного процесса и не вызывает
     * уведомления об изменении состояния.</p>
     *
     * <p>Состояние конкретного топливного хранилища
     * не входит в сохраняемое состояние
     * данного производственного процесса.</p>
     *
     * @param output выходной объект для записи состояния
     *               производственного процесса
     * @throws NullPointerException если output равен
     *                              {@code null}
     */
    @Override
    public void saveState(@NonNull ValueOutput output) {
        Objects.requireNonNull(output, "output cannot be null");

        ValueOutput fuelCycleOutput = output.child(FUEL_CYCLE_KEY);
        this.fuelCycle.serialize(fuelCycleOutput);
    }

    /**
     * Восстанавливает состояние топливного
     * производственного процесса.
     *
     * <p>Получает вложенную секцию {@code fuel_cycle}
     * из предоставленного объекта чтения и делегирует
     * восстановление состояния компоненту
     * {@link FuelCycleComponent}.</p>
     *
     * <p>Если соответствующая секция отсутствует
     * или имеет несовместимый тип, компоненту передаётся
     * пустой объект чтения, что приводит к сбросу
     * состояния топливного цикла.</p>
     *
     * <p>Проверка наличия обязательных полей,
     * их исходных NBT-типов и соблюдения инвариантов
     * топливного цикла выполняется непосредственно
     * компонентом.</p>
     *
     * <p>Восстановление выполняется тихо, без потребления
     * топлива, открытия транзакций, запуска нового цикла
     * и вызова уведомлений об изменении состояния.</p>
     *
     * <p>Метод предназначен для восстановления состояния
     * до начала штатной работы производственного процесса
     * при отсутствии незавершённых транзакций,
     * затрагивающих топливный цикл.</p>
     *
     * @param input входной объект с сохранённым состоянием
     *              производственного процесса
     * @throws NullPointerException если input равен
     *                              {@code null}
     */
    @Override
    public void restoreState(@NonNull ValueInput input) {
        Objects.requireNonNull(input, "input cannot be null");

        ValueInput fuelCycleInput = input.childOrEmpty(FUEL_CYCLE_KEY);
        this.fuelCycle.deserialize(fuelCycleInput);
    }
}
