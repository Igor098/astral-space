package ru.greatdragonx.astralspace.common.energy.port;

import org.jspecify.annotations.NonNull;

import java.util.Objects;

/**
 * Определяет правила доступа и допустимые режимы работы
 * энергетических портов механизма.
 *
 * <p>Политика отвечает за определение текущего режима порта,
 * его доступности и возможности изменения конфигурации.</p>
 *
 * <p>Поддерживаются три режима:
 * {@link EnergyPortMode#INPUT},
 * {@link EnergyPortMode#OUTPUT} и
 * {@link EnergyPortMode#DISABLED}.
 * Одновременный приём и вывод энергии через один порт
 * не допускается.</p>
 *
 * <p>Политика может использоваться как механизмами
 * с фиксированными портами, так и механизмами
 * с пользовательской настройкой направлений передачи.</p>
 *
 * <p>Доступность порта не зависит от возможности изменения
 * его режима. Например, фиксированный выход мультиблочного
 * генератора может быть недоступен до формирования
 * необходимой структуры.</p>
 *
 * <p>Для неизвестных идентификаторов реализации должны
 * возвращать {@link EnergyPortMode#DISABLED} из
 * {@link #getMode(EnergyPortId)} и {@code false}
 * из {@link #isAvailable(EnergyPortId)} и
 * {@link #canChangeMode(EnergyPortId, EnergyPortMode)}.</p>
 *
 * <p>Политика не выполняет передачу энергии, не управляет
 * энергетическим хранилищем и не изменяет настройки
 * портов самостоятельно.</p>
 *
 * <p>Проверки разрешений должны выполняться непосредственно
 * при энергетических операциях, чтобы ранее полученные
 * обработчики не могли обойти изменившиеся ограничения.</p>
 */
public interface EnergyPortPolicy {

    /**
     * Возвращает текущий режим указанного энергетического порта.
     *
     * <p>Режим определяет допустимое направление передачи
     * энергии, но сам по себе не гарантирует физическую
     * доступность порта.</p>
     *
     * <p>Для неизвестного идентификатора реализация должна
     * возвращать {@link EnergyPortMode#DISABLED}.</p>
     *
     * @param portId идентификатор энергетического порта
     * @return текущий режим порта;
     * {@link EnergyPortMode#DISABLED},
     * если порт неизвестен
     * @throws NullPointerException если {@code portId == null}
     */
    EnergyPortMode getMode(@NonNull EnergyPortId portId);

    /**
     * Проверяет текущую доступность энергетического порта.
     *
     * <p>Доступность может зависеть от состояния механизма,
     * наличия необходимых компонентов, формирования
     * мультиблочной структуры и других условий.</p>
     *
     * <p>Метод не проверяет направление передачи энергии.
     * Порт в режиме {@link EnergyPortMode#DISABLED}
     * может оставаться физически доступным.</p>
     *
     * <p>Для неизвестного идентификатора реализация должна
     * возвращать {@code false}.</p>
     *
     * @param portId идентификатор энергетического порта
     * @return {@code true}, если порт существует
     * и в данный момент доступен;
     * иначе {@code false}
     * @throws NullPointerException если {@code portId == null}
     */
    boolean isAvailable(@NonNull EnergyPortId portId);

    /**
     * Проверяет возможность изменения режима энергетического порта.
     *
     * <p>Для портов с фиксированным режимом метод должен
     * возвращать {@code false}, даже если запрошенный режим
     * совпадает с текущим.</p>
     *
     * <p>Для настраиваемых портов результат определяется
     * набором допустимых режимов конкретного механизма.</p>
     *
     * <p>Проверка не зависит от текущей физической доступности
     * порта. Недоступность порта сама по себе не означает,
     * что изменение его конфигурации запрещено.</p>
     *
     * <p>Метод не изменяет состояние порта.
     * Изменение конфигурации выполняется владельцем
     * механизма после соответствующей проверки.</p>
     *
     * <p>Для неизвестного идентификатора реализация должна
     * возвращать {@code false}.</p>
     *
     * @param portId  идентификатор энергетического порта
     * @param newMode запрашиваемый режим работы порта
     * @return {@code true}, если изменение режима разрешено;
     * иначе {@code false}
     * @throws NullPointerException если {@code portId}
     *                              или {@code newMode} равен null
     */
    boolean canChangeMode(
        @NonNull EnergyPortId portId,
        @NonNull EnergyPortMode newMode
    );

    /**
     * Проверяет возможность приёма энергии через указанный порт.
     *
     * <p>Приём разрешён только при одновременном выполнении
     * двух условий:</p>
     *
     * <ul>
     *   <li>Порт доступен согласно {@link #isAvailable(EnergyPortId)}.</li>
     *   <li>Текущий режим разрешает приём энергии.</li>
     * </ul>
     *
     * <p>Метод не учитывает свободную ёмкость хранилища
     * и ограничения скорости передачи энергии.</p>
     *
     * @param portId идентификатор энергетического порта
     * @return {@code true}, если приём энергии разрешён;
     * иначе {@code false}
     * @throws NullPointerException если {@code portId == null}
     */
    default boolean allowsInsert(@NonNull EnergyPortId portId) {
        Objects.requireNonNull(
            portId,
            "portId cannot be null"
        );

        return isAvailable(portId) && getMode(portId).allowsInsert();
    }

    /**
     * Проверяет возможность выдачи энергии через указанный порт.
     *
     * <p>Выдача разрешена только при одновременном выполнении
     * двух условий:</p>
     *
     * <ul>
     *   <li>Порт доступен согласно {@link #isAvailable(EnergyPortId)}.</li>
     *   <li>Текущий режим разрешает выдачу энергии.</li>
     * </ul>
     *
     * <p>Метод не учитывает текущий запас энергии,
     * общий бюджет вывода за тик и правила справедливого
     * распределения между портами.</p>
     *
     * @param portId идентификатор энергетического порта
     * @return {@code true}, если выдача энергии разрешена;
     * иначе {@code false}
     * @throws NullPointerException если {@code portId == null}
     */
    default boolean allowsExtract(@NonNull EnergyPortId portId) {
        Objects.requireNonNull(
            portId,
            "portId cannot be null"
        );

        return isAvailable(portId) && getMode(portId).allowsExtract();
    }
}

