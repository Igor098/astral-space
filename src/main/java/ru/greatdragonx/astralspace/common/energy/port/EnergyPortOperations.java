package ru.greatdragonx.astralspace.common.energy.port;

import net.neoforged.neoforge.transfer.transaction.TransactionContext;
import org.jspecify.annotations.NonNull;

/**
 * Контракт энергетических операций механизма,
 * доступных через его логические энергетические порты.
 *
 * <p>Предоставляет единый доступ к текущему запасу
 * энергии, ёмкости общего энергетического хранилища,
 * а также операциям внешнего приёма и извлечения
 * энергии.</p>
 *
 * <p>Операции передачи выполняются с указанием
 * логического идентификатора порта, что позволяет
 * учитывать его режим, доступность и ограничения
 * передачи энергии.</p>
 *
 * <p>Допускается частичное выполнение операций
 * приёма и извлечения энергии. При невозможности
 * выполнить операцию возвращается {@code 0}.</p>
 *
 * <p>Операции передачи выполняются в рамках
 * предоставленного транзакционного контекста.
 * Управление жизненным циклом транзакции
 * является ответственностью вызывающего кода.</p>
 *
 * <p>Интерфейс не определяет физическое расположение
 * портов, устройство энергетического хранилища
 * и конкретные алгоритмы распределения энергии.</p>
 *
 * @see EnergyPortId
 * @see EnergyPortHandler
 * @see EnergyPortPolicy
 */
public interface EnergyPortOperations {
    /**
     * Возвращает текущее количество энергии
     * в общем энергетическом хранилище механизма.
     *
     * <p>Возвращаемое значение не ограничивается
     * диапазоном {@code int}.</p>
     *
     * <p>В рамках незавершённой транзакции может
     * возвращаться предварительное состояние
     * энергетического хранилища.</p>
     *
     * @return текущее количество хранимой энергии, FE
     */
    long getStoredEnergy();

    /**
     * Возвращает максимальную ёмкость общего
     * энергетического хранилища механизма.
     *
     * <p>Значение характеризует вместимость
     * хранилища, а не доступную скорость передачи
     * энергии через отдельный порт.</p>
     *
     * @return максимальная ёмкость энергетического
     * хранилища, FE
     */
    long getCapacity();

    /**
     * Выполняет внешний приём энергии через
     * указанный логический энергетический порт.
     *
     * <p>Фактически принятое количество энергии
     * может быть меньше запрошенного в зависимости
     * от свободной ёмкости хранилища, режима
     * и доступности порта, а также действующих
     * ограничений передачи.</p>
     *
     * <p>Если приём энергии невозможен или
     * запрошенное количество равно {@code 0},
     * возвращает {@code 0}.</p>
     *
     * <p>Изменения энергетического состояния
     * выполняются транзакционно и должны
     * отменяться при откате транзакции.</p>
     *
     * <p>Метод не подтверждает и не закрывает
     * предоставленную транзакцию.</p>
     *
     * @param portId      идентификатор энергетического порта
     * @param amount      запрошенное количество энергии, FE
     * @param transaction контекст транзакции приёма энергии
     * @return фактически принятое количество энергии
     * в диапазоне от {@code 0} до {@code amount}
     * @throws NullPointerException     если portId или
     *                                  transaction равен
     *                                  {@code null}
     * @throws IllegalArgumentException если amount
     *                                  отрицателен
     */
    int insert(@NonNull EnergyPortId portId, int amount, @NonNull TransactionContext transaction);

    /**
     * Выполняет внешнее извлечение энергии через
     * указанный логический энергетический порт.
     *
     * <p>Фактически извлечённое количество энергии
     * может быть меньше запрошенного в зависимости
     * от доступного запаса энергии, режима
     * и доступности порта, а также действующих
     * ограничений передачи.</p>
     *
     * <p>Если извлечение энергии невозможно или
     * запрошенное количество равно {@code 0},
     * возвращает {@code 0}.</p>
     *
     * <p>Изменения энергетического состояния
     * выполняются транзакционно и должны
     * отменяться при откате транзакции.</p>
     *
     * <p>Метод не подтверждает и не закрывает
     * предоставленную транзакцию.</p>
     *
     * @param portId      идентификатор энергетического порта
     * @param amount      запрошенное количество энергии, FE
     * @param transaction контекст транзакции извлечения
     *                    энергии
     * @return фактически извлечённое количество энергии
     * в диапазоне от {@code 0} до {@code amount}
     * @throws NullPointerException     если portId или
     *                                  transaction равен
     *                                  {@code null}
     * @throws IllegalArgumentException если amount
     *                                  отрицателен
     */
    int extract(@NonNull EnergyPortId portId, int amount, @NonNull TransactionContext transaction);
}
