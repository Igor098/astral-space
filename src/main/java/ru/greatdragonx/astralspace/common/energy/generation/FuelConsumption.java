package ru.greatdragonx.astralspace.common.energy.generation;

import net.neoforged.neoforge.transfer.transaction.TransactionContext;

import java.util.OptionalInt;

/**
 * Определяет транзакционную операцию потребления топлива
 * для запуска нового топливного цикла.
 *
 * <p>Позволяет отделить общий алгоритм управления
 * топливным циклом от конкретного способа хранения,
 * проверки пригодности и списания топлива.</p>
 *
 * <p>Конкретная реализация самостоятельно определяет
 * необходимое количество топлива и продолжительность
 * производственного цикла, оплачиваемого этим топливом.</p>
 *
 * <p>Операция выполняется в предоставленном
 * транзакционном контексте. Управление жизненным циклом
 * корневой транзакции осуществляется вызывающим кодом.</p>
 *
 * <p>Интерфейс не отвечает за запуск топливного цикла,
 * учёт оставшихся производственных тиков, производство,
 * хранение и передачу энергии.</p>
 *
 * @see FuelCycleGenerationProcess
 * @see FuelCycleComponent
 */
@FunctionalInterface
public interface FuelConsumption {
    /**
     * Пытается списать количество топлива, необходимое
     * для запуска одного нового топливного цикла.
     *
     * <p>Все изменения состояния топливных хранилищ
     * должны выполняться в рамках предоставленного
     * транзакционного контекста и поддерживать откат.</p>
     *
     * <p>При полном успешном списании необходимого
     * количества топлива возвращается строго положительная
     * длительность оплаченного топливного цикла
     * в производственных тиках.</p>
     *
     * <p>Возвращение положительной длительности означает
     * успешное извлечение всей необходимой порции топлива
     * в рамках текущей транзакции, но не окончательное
     * подтверждение произведённых изменений.</p>
     *
     * <p>Если необходимое количество топлива невозможно
     * списать полностью, возвращается
     * {@link OptionalInt#empty()}.</p>
     *
     * <p>При частичном списании топлива реализация также
     * должна вернуть пустой результат. Предварительные
     * изменения будут отменены вызывающим кодом
     * при откате транзакции.</p>
     *
     * <p>Реализация не должна самостоятельно открывать
     * независимую корневую транзакцию, подтверждать
     * или закрывать предоставленную транзакцию.</p>
     *
     * <p>Уведомления об успешном изменении состояния
     * топливного хранилища не должны публиковаться
     * до окончательного подтверждения корневой
     * транзакции.</p>
     *
     * <p>Возвращение {@code null}, нулевой или отрицательной
     * длительности является нарушением контракта.
     * Возвращение положительной длительности при неполном
     * списании топлива также является нарушением
     * контракта.</p>
     *
     * @param transaction ненулевой транзакционный контекст,
     *                    в котором выполняется
     *                    списание топлива
     * @return строго положительная длительность
     * оплаченного топливного цикла либо пустой
     * {@link OptionalInt}, если необходимое
     * количество топлива не удалось списать
     */
    OptionalInt tryConsume(TransactionContext transaction);
}
