package ru.greatdragonx.astralspace.common.fluid.port;

import org.jspecify.annotations.NonNull;

import java.util.Objects;

/**
 * Определяет правила доступа и допустимые режимы работы
 * жидкостных портов механизма.
 *
 * <p>Политика отвечает за определение текущего режима порта,
 * его доступности и возможности изменения конфигурации.</p>
 *
 * <p>Поддерживаются четыре взаимоисключающих режима:
 * {@link FluidPortMode#INPUT},
 * {@link FluidPortMode#OUTPUT},
 * {@link FluidPortMode#DISABLED} и
 * {@link FluidPortMode#SERVICE}.</p>
 *
 * <p>Каждый жидкостный порт может использовать только один
 * режим одновременно. Приём и вывод жидкости через один
 * порт в одно и то же время не допускаются.</p>
 *
 * <p>Режим {@link FluidPortMode#SERVICE} предназначен
 * для специального извлечения жидкости из разрешённых
 * входных резервуаров. Обычный режим
 * {@link FluidPortMode#OUTPUT} предоставляет доступ
 * только к выходным резервуарам.</p>
 *
 * <p>Политика может применяться как к механизмам
 * с фиксированными портами, так и к механизмам
 * с пользовательской настройкой направлений.</p>
 *
 * <p>Доступность порта не зависит от возможности
 * изменения его режима. Например, порт мультиблока
 * может быть временно недоступен до формирования
 * необходимой структуры.</p>
 *
 * <p>Для неизвестных идентификаторов реализации должны
 * возвращать {@link FluidPortMode#DISABLED} из
 * {@link #getMode(FluidPortId)} и {@code false}
 * из {@link #isAvailable(FluidPortId)} и
 * {@link #canChangeMode(FluidPortId, FluidPortMode)}.</p>
 *
 * <p>Политика не хранит жидкость, не выполняет её передачу,
 * не изменяет настройки портов самостоятельно
 * и не управляет Minecraft capabilities.</p>
 *
 * <p>Ограничения доступа должны проверяться при каждой
 * внешней операции, чтобы ранее полученные обработчики
 * не могли обойти изменившиеся настройки.</p>
 */
public interface FluidPortPolicy {

    /**
     * Возвращает текущий режим указанного жидкостного порта.
     *
     * <p>Режим определяет разрешённое направление передачи
     * жидкости, но сам по себе не гарантирует физическую
     * доступность порта.</p>
     *
     * <p>Для неизвестного идентификатора реализация должна
     * возвращать {@link FluidPortMode#DISABLED}.</p>
     *
     * <p>Метод не проверяет наличие жидкости в резервуаре
     * или возможность её приёма.</p>
     *
     * @param portId идентификатор жидкостного порта
     * @return текущий режим порта или
     * {@link FluidPortMode#DISABLED},
     * если порт неизвестен
     * @throws NullPointerException если {@code portId}
     *                              равен {@code null}
     */
    FluidPortMode getMode(@NonNull FluidPortId portId);

    /**
     * Проверяет текущую доступность жидкостного порта.
     *
     * <p>Доступность может зависеть от состояния механизма,
     * наличия необходимых компонентов, формирования
     * мультиблочной структуры и других условий.</p>
     *
     * <p>Метод не проверяет направление передачи жидкости.
     * Порт в режиме {@link FluidPortMode#DISABLED}
     * может оставаться физически доступным.</p>
     *
     * <p>Для неизвестного идентификатора реализация должна
     * возвращать {@code false}.</p>
     *
     * @param portId идентификатор жидкостного порта
     * @return {@code true}, если порт существует
     * и в данный момент доступен;
     * иначе {@code false}
     * @throws NullPointerException если {@code portId}
     *                              равен {@code null}
     */
    boolean isAvailable(@NonNull FluidPortId portId);

    /**
     * Проверяет возможность изменения режима
     * указанного жидкостного порта.
     *
     * <p>Для портов с фиксированным режимом метод должен
     * возвращать {@code false}, даже если запрошенный
     * режим совпадает с текущим.</p>
     *
     * <p>Для настраиваемых портов результат определяется
     * набором допустимых режимов конкретного механизма.</p>
     *
     * <p>Проверка не зависит от текущей физической
     * доступности порта. Временная недоступность
     * не обязательно запрещает изменение конфигурации.</p>
     *
     * <p>Метод не изменяет состояние порта.
     * Изменение выполняется владельцем механизма
     * после проверки политики.</p>
     *
     * <p>Для неизвестного идентификатора реализация должна
     * возвращать {@code false}.</p>
     *
     * @param portId  идентификатор жидкостного порта
     * @param newMode запрашиваемый режим работы порта
     * @return {@code true}, если изменение режима разрешено;
     * иначе {@code false}
     * @throws NullPointerException если {@code portId}
     *                              или {@code newMode}
     *                              равен {@code null}
     */
    boolean canChangeMode(
        @NonNull FluidPortId portId,
        @NonNull FluidPortMode newMode
    );

    /**
     * Проверяет возможность подачи жидкости
     * через указанный порт.
     *
     * <p>Подача разрешена только при одновременном
     * выполнении двух условий:</p>
     *
     * <ul>
     *   <li>Порт доступен согласно
     *       {@link #isAvailable(FluidPortId)}.</li>
     *   <li>Текущий режим разрешает приём жидкости.</li>
     * </ul>
     *
     * <p>Метод не проверяет свободную ёмкость резервуара,
     * допустимость конкретной жидкости, ограничения
     * рецепта и скорость передачи.</p>
     *
     * @param portId идентификатор жидкостного порта
     * @return {@code true}, если подача жидкости разрешена;
     * иначе {@code false}
     * @throws NullPointerException если {@code portId}
     *                              равен {@code null}
     */
    default boolean allowsInsert(@NonNull FluidPortId portId) {
        Objects.requireNonNull(
            portId,
            "portId cannot be null"
        );

        return isAvailable(portId) && getMode(portId).allowsInsert();
    }

    /**
     * Проверяет возможность извлечения жидкости
     * через указанный порт.
     *
     * <p>Извлечение разрешено только при одновременном
     * выполнении двух условий:</p>
     *
     * <ul>
     *   <li>Порт доступен согласно
     *       {@link #isAvailable(FluidPortId)}.</li>
     *   <li>Текущий режим разрешает извлечение жидкости.</li>
     * </ul>
     *
     * <p>Извлечение допускается в режимах
     * {@link FluidPortMode#OUTPUT} и
     * {@link FluidPortMode#SERVICE}. При этом режим
     * OUTPUT предоставляет доступ к выходным резервуарам,
     * а SERVICE — к специально разрешённым
     * входным резервуарам.</p>
     *
     * <p>Метод не выбирает конкретный резервуар,
     * не проверяет количество жидкости, её тип,
     * резервирование и ограничения скорости передачи.</p>
     *
     * @param portId идентификатор жидкостного порта
     * @return {@code true}, если извлечение разрешено;
     * иначе {@code false}
     * @throws NullPointerException если {@code portId}
     *                              равен {@code null}
     */
    default boolean allowsExtract(@NonNull FluidPortId portId) {
        Objects.requireNonNull(
            portId,
            "portId cannot be null"
        );

        return isAvailable(portId) && getMode(portId).allowsExtract();
    }
}
