package ru.greatdragonx.astralspace.common.fluid.storage;

/**
 * Определяет производственную роль жидкостного
 * резервуара внутри механизма.
 *
 * <p>Роль описывает назначение резервуара
 * в производственном процессе и не является
 * режимом внешнего доступа к жидкости.</p>
 *
 * <p>Внешние направления передачи определяются
 * отдельно через {@link ru.greatdragonx.astralspace.common.fluid.port.FluidPortMode}
 * и соответствующие политики портов.</p>
 *
 * <p>Роль резервуара сама по себе не разрешает
 * и не запрещает операции хранения жидкости.
 * Ограничения внешнего доступа применяются
 * отдельным обработчиком портов.</p>
 */
public enum FluidTankRole {
    /**
     * Резервуар для входных жидкостей,
     * используемых механизмом в производстве.
     */
    INPUT,

    /**
     * Резервуар для жидкостей, получаемых
     * в результате работы механизма.
     */
    OUTPUT,

    /**
     * Универсальный резервуар, который может
     * использоваться как для приёма, так и для
     * выдачи жидкости, если это предусмотрено
     * конструкцией механизма.
     *
     * <p>Данная роль не создаёт двунаправленный
     * режим внешнего жидкостного порта.</p>
     */
    BIDIRECTIONAL
}
